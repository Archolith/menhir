def test_refresh_is_cas_guarded(beacon_python: str, tmp_path: Path) -> None:
    repo = _fixture_repo(tmp_path)
    reader = _reader(root=str(repo))
    first = generate_beacon(reader, "fixture", repo, beacon_python=beacon_python)
    target = repo / "beacon.generated.yaml"
    original = target.read_bytes()

    wrong = "0" * 64
    with pytest.raises(BeaconGenerationError, match="does not match existing"):
        generate_beacon(
            reader,
            "fixture",
            repo,
            beacon_python=beacon_python,
            refresh=True,
            expected_sha256=wrong,
        )

    refreshed = generate_beacon(
        reader,
        "fixture",
        repo,
        beacon_python=beacon_python,
        refresh=True,
        expected_sha256=first.sha256,
    )
    assert refreshed.created is False
    assert refreshed.sha256 == first.sha256
    assert target.read_bytes() == original  # unchanged rebuild: byte-identical


