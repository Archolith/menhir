def test_source_edit_during_beacon_build_refuses_publication(
    beacon_python: str, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    repo = _fixture_repo(tmp_path)
    reader = _reader(root=str(repo))
    first = generate_beacon(reader, "fixture", repo, beacon_python=beacon_python)
    target = repo / "beacon.generated.yaml"
    original = target.read_bytes()
    real_build = generation_module.build_manifest_via_beacon

    def build_then_edit(*args, **kwargs):
        payload = real_build(*args, **kwargs)
        (repo / "README.md").write_text("# Edited during Beacon build\n", encoding="utf-8")
        return payload

    monkeypatch.setattr(generation_module, "build_manifest_via_beacon", build_then_edit)
    with pytest.raises(BeaconGenerationError, match="stale"):
        generate_beacon(
            reader,
            "fixture",
            repo,
            beacon_python=beacon_python,
            refresh=True,
            expected_sha256=first.sha256,
        )
    assert target.read_bytes() == original


def test_reingest_during_beacon_build_refuses_publication(
    beacon_python: str, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    repo = _fixture_repo(tmp_path)
    reader = _reader(root=str(repo))
    first = generate_beacon(reader, "fixture", repo, beacon_python=beacon_python)
    target = repo / "beacon.generated.yaml"
    original = target.read_bytes()
    real_build = generation_module.build_manifest_via_beacon

    def build_then_reingest(*args, **kwargs):
        payload = real_build(*args, **kwargs)
        reader._guard_state["writer_revision"] = "writer-2"
        return payload

    monkeypatch.setattr(
        generation_module, "build_manifest_via_beacon", build_then_reingest
    )
    with pytest.raises(BeaconGenerationError, match="structure changed"):
        generate_beacon(
            reader,
            "fixture",
            repo,
            beacon_python=beacon_python,
            refresh=True,
            expected_sha256=first.sha256,
        )
    assert target.read_bytes() == original


def test_changed_source_fact_changes_only_its_claim(
    beacon_python: str, tmp_path: Path
) -> None:
    repo = _fixture_repo(tmp_path)
    reader = _reader(root=str(repo))
    generate_beacon(reader, "fixture", repo, beacon_python=beacon_python)
    before = (repo / "beacon.generated.yaml").read_text(encoding="utf-8")

    changed = _reader(
        root=str(repo),
        overview={
            "description": "A changed evidence dump description.",
            "stack": "python",
            "entities": {"file": 3},
            "edges": {"IMPORTS": 2},
            "coverage": {"known": True},
            "contains_repos": [],
        },
    )
    generate_beacon(
        changed,
        "fixture",
        repo,
        beacon_python=beacon_python,
        refresh=True,
        expected_sha256=hashlib.sha256(before.encode("utf-8")).hexdigest(),
    )
    after = (repo / "beacon.generated.yaml").read_text(encoding="utf-8")

    before_lines = before.splitlines()
    after_lines = after.splitlines()
    assert len(before_lines) == len(after_lines)
    changed_indexes = [
        index for index, (a, b) in enumerate(zip(before_lines, after_lines)) if a != b
    ]
    assert changed_indexes, "the changed fact must be reflected"
    for index in changed_indexes:
        assert "Fixture project for the evidence dump." in before_lines[index]
        assert "A changed evidence dump description." in after_lines[index]


def test_artifact_serves_without_menhir(beacon_python: str, tmp_path: Path) -> None:
    """Validate and export the artifact with Menhir completely out of the loop."""
    repo = _fixture_repo(tmp_path)
    generate_beacon(
        _reader(root=str(repo)), "fixture", repo, beacon_python=beacon_python
    )
    manifest = repo / "beacon.generated.yaml"

    probe = subprocess.run(  # nosec B603 - fixed argv, local fixture only
        [beacon_python, "-m", "beacon", "validate", str(manifest)],
        capture_output=True,
        check=False,
        cwd=str(repo),
    )
    assert probe.returncode == 0, probe.stderr.decode("utf-8", errors="replace")
    assert b"0 errors" in probe.stdout

    # Export is publication-strict: the two known-absent intent warnings must
    # be acknowledged (with the same fixed reasons the build used).
    ack_guardrails = "--acknowledge=guardrails_missing=generated from source evidence"
    ack_test = "--acknowledge=test_command_missing=generated from source evidence"
    exported = subprocess.run(  # nosec B603 - fixed argv, local fixture only
        [
            beacon_python,
            "-m",
            "beacon",
            "export",
            str(manifest),
            "--output",
            "-",
            ack_guardrails,
            ack_test,
        ],
        capture_output=True,
        check=False,
        cwd=str(repo),
    )
    assert exported.returncode == 0, exported.stderr.decode("utf-8", errors="replace")
    assert b'"beacon_snapshot_version":"1.0"' in exported.stdout


def test_cli_reader_uses_canonical_structure_adapter(monkeypatch: pytest.MonkeyPatch) -> None:
    """Exercise the real lazy adapter import without opening a database connection."""
    from menhir.cli.beacon import _reader as cli_reader
    from menhir.config.settings_model import MemorySettings
    from menhir.infrastructure.structure_queries import StructureGraphWriter

    settings = SimpleNamespace(
        neo4j_uri="bolt://127.0.0.1:7689",
        neo4j_user="neo4j",
        neo4j_password="fixture-only",
        neo4j_database="neo4j",
    )
    monkeypatch.setattr("menhir.env_file.load_menhir_env", lambda: None)
    monkeypatch.setattr(MemorySettings, "from_env", staticmethod(lambda: settings))
    reader, repository = cli_reader()
    try:
        assert isinstance(reader, StructureGraphWriter)
        assert reader.neo4j is repository
        assert repository.uri == settings.neo4j_uri
        for method in (
            "get_project_root_path", "get_project_coverage", "get_scan_fingerprint",
            "query_overview", "query_files", "query_documents", "get_beacon_evidence_guard",
        ):
            assert callable(getattr(reader, method))
    finally:
        repository.close()
